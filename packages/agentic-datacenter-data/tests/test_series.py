"""Measured input series: manifest, hashes, units, interpolation, gaps and range.

Every series here is synthetic and written by the test itself.
"""

import hashlib
import json
from collections.abc import Sequence
from pathlib import Path

import pytest

from agentic_datacenter.data import (
    DatasetFileMissing,
    GapTooLong,
    HashMismatch,
    ManifestInvalid,
    OutsideSeries,
    UnitNotUnderstood,
    load_series,
    parse_utc_ms,
    write_manifest,
)

T0 = "2020-07-01T00:00:00Z"
T0_MS = parse_utc_ms(T0)
H = 3_600_000


def write(
    directory: Path,
    values: Sequence[str],
    *,
    columns: Sequence[str] = ("dry_bulb",),
    units: dict[str, str] | None = None,
    gap_tolerance_s: int = 0,
) -> Path:
    """Write an hourly series from 2020-07-01T00:00Z and its manifest; return the manifest."""
    directory.mkdir(parents=True, exist_ok=True)
    lines = ["time_utc," + ",".join(columns)]
    for i, value in enumerate(values):
        cells = value if isinstance(value, tuple) else (value,)
        lines.append(f"2020-07-01T{i:02d}:00:00Z," + ",".join(cells))
    series = directory / "series.csv"
    series.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return write_manifest(
        series,
        dataset_id="synthetic_site",
        title="Synthetic hourly weather written by a test",
        source="generated by the test suite",
        version="1",
        licence="none; synthetic test data",
        redistribution="not_cleared",
        quality_status="synthetic",
        units=units or {c: ("%" if c == "rel_humidity" else "degC") for c in columns},
        gap_tolerance_s=gap_tolerance_s,
    )


def edit_manifest(path: Path, **changes: object) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    data.update(changes)
    path.write_text(json.dumps(data), encoding="utf-8")


# --- reading and interpolation -------------------------------------------------------


def test_value_at_an_hour_is_the_sample(tmp_path: Path) -> None:
    series = load_series(write(tmp_path, ["20.0", "22.0", "26.0"]))
    assert series.value_at("dry_bulb", T0_MS) == 20.0
    assert series.value_at("dry_bulb", T0_MS + H) == 22.0
    assert series.value_at("dry_bulb", T0_MS + 2 * H) == 26.0


def test_value_between_hours_is_linear(tmp_path: Path) -> None:
    series = load_series(write(tmp_path, ["20.0", "22.0", "26.0"]))
    assert series.value_at("dry_bulb", T0_MS + H // 2) == pytest.approx(21.0)
    assert series.value_at("dry_bulb", T0_MS + H // 4) == pytest.approx(20.5)
    assert series.value_at("dry_bulb", T0_MS + H + 900_000) == pytest.approx(23.0)
    assert series.value_at("dry_bulb", T0_MS + 2 * H - 1000) == pytest.approx(26.0 - 4.0 / 3600)


def test_period_and_identity_come_from_the_file(tmp_path: Path) -> None:
    manifest = write(tmp_path, ["20.0", "22.0", "26.0"])
    series = load_series(manifest)
    assert (series.start_ms, series.end_ms) == (T0_MS, T0_MS + 2 * H)
    assert series.columns == ("dry_bulb",)
    assert series.manifest_sha256 == hashlib.sha256(manifest.read_bytes()).hexdigest()
    sha = hashlib.sha256((tmp_path / "series.csv").read_bytes()).hexdigest()
    assert series.provenance()["files"] == {"series.csv": sha}


@pytest.mark.parametrize(
    ("unit", "raw", "expected"),
    [("degC", "25.0", 25.0), ("K", "298.15", 25.0), ("degF", "77.0", 25.0)],
)
def test_temperature_units_are_converted_to_celsius(
    tmp_path: Path, unit: str, raw: str, expected: float
) -> None:
    series = load_series(write(tmp_path, [raw, raw], units={"dry_bulb": unit}))
    assert series.value_at("dry_bulb", T0_MS) == pytest.approx(expected)


def test_humidity_column_is_read_beside_the_temperature(tmp_path: Path) -> None:
    manifest = write(
        tmp_path, [("20.0", "40.0"), ("22.0", "60.0")], columns=("dry_bulb", "rel_humidity")
    )
    series = load_series(manifest)
    assert series.value_at("rel_humidity", T0_MS + H // 2) == pytest.approx(50.0)


def test_the_manifest_is_written_with_period_hashes_and_licence(tmp_path: Path) -> None:
    manifest = write(tmp_path, ["20.0", "22.0"])
    data = json.loads(manifest.read_text(encoding="utf-8"))
    assert data["period"] == {"start_utc": T0, "end_utc": "2020-07-01T01:00:00Z"}
    assert data["licence"] == "none; synthetic test data"
    assert data["redistribution"] == "not_cleared"
    assert [f["path"] for f in data["files"]] == ["series.csv"]


# --- gaps ----------------------------------------------------------------------------


def test_a_gap_inside_the_tolerance_is_bridged_and_reported(tmp_path: Path) -> None:
    series = load_series(write(tmp_path, ["20.0", "", "24.0"], gap_tolerance_s=3600))
    assert series.value_at("dry_bulb", T0_MS + H) == pytest.approx(22.0)
    assert series.gaps("dry_bulb", T0_MS, T0_MS + 2 * H) == [(T0_MS, T0_MS + 2 * H)]
    assert series.provenance()["bridged_gaps"]["dry_bulb"] == {"count": 1, "longest_s": 3600}


def test_a_gap_larger_than_the_tolerance_fails(tmp_path: Path) -> None:
    series = load_series(write(tmp_path, ["20.0", "", "", "26.0"], gap_tolerance_s=3600))
    assert series.value_at("dry_bulb", T0_MS) == 20.0
    with pytest.raises(GapTooLong, match=r"dry_bulb.*7200 s.*tolerance of 3600 s"):
        series.value_at("dry_bulb", T0_MS + H + 1)


def test_no_gap_is_bridged_when_the_tolerance_is_zero(tmp_path: Path) -> None:
    series = load_series(write(tmp_path, ["20.0", "", "24.0"]))
    with pytest.raises(GapTooLong, match="tolerance of 0 s"):
        series.value_at("dry_bulb", T0_MS + H)


def test_a_missing_row_is_a_gap_like_an_empty_cell(tmp_path: Path) -> None:
    lines = ["time_utc,dry_bulb", f"{T0},20.0", "2020-07-01T02:00:00Z,24.0"]
    (tmp_path / "series.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    manifest = write_manifest(
        tmp_path / "series.csv", dataset_id="synthetic_site", title="t", source="test",
        version="1", licence="none", redistribution="not_cleared", quality_status="synthetic",
        units={"dry_bulb": "degC"}, gap_tolerance_s=0,
    )  # fmt: skip
    with pytest.raises(GapTooLong):
        load_series(manifest).value_at("dry_bulb", T0_MS + H)


# --- range ---------------------------------------------------------------------------


def test_time_before_or_after_the_series_is_refused(tmp_path: Path) -> None:
    series = load_series(write(tmp_path, ["20.0", "22.0"]))
    with pytest.raises(OutsideSeries, match="before the series starts"):
        series.value_at("dry_bulb", T0_MS - 1)
    with pytest.raises(OutsideSeries, match="after the series ends"):
        series.value_at("dry_bulb", T0_MS + H + 1)


def test_a_trailing_empty_value_is_not_extrapolated(tmp_path: Path) -> None:
    series = load_series(write(tmp_path, ["20.0", "22.0", ""], gap_tolerance_s=7200))
    with pytest.raises(OutsideSeries, match="no measured value of dry_bulb after"):
        series.value_at("dry_bulb", T0_MS + H + 1)


# --- refusals at load time -----------------------------------------------------------


def test_missing_manifest_is_named(tmp_path: Path) -> None:
    with pytest.raises(DatasetFileMissing, match="dataset_manifest.json"):
        load_series(tmp_path / "dataset_manifest.json")


def test_missing_series_file_is_named(tmp_path: Path) -> None:
    manifest = write(tmp_path, ["20.0", "22.0"])
    (tmp_path / "series.csv").unlink()
    with pytest.raises(DatasetFileMissing, match=r"series\.csv"):
        load_series(manifest)


def test_hash_mismatch_is_named_with_both_hashes(tmp_path: Path) -> None:
    manifest = write(tmp_path, ["20.0", "22.0"])
    expected = json.loads(manifest.read_text())["files"][0]["sha256"]
    (tmp_path / "series.csv").write_text(f"time_utc,dry_bulb\n{T0},21.0\n", encoding="utf-8")
    with pytest.raises(HashMismatch, match=rf"series\.csv.*{expected}"):
        load_series(manifest)


def test_unit_not_understood_is_named(tmp_path: Path) -> None:
    manifest = write(tmp_path, ["20.0", "22.0"])
    edit_manifest(manifest, columns={"dry_bulb": {"unit": "Rankine"}})
    with pytest.raises(UnitNotUnderstood, match=r"dry_bulb.*Rankine.*degC"):
        load_series(manifest)


def test_an_unknown_column_is_refused(tmp_path: Path) -> None:
    manifest = write(tmp_path, ["20.0", "22.0"])
    edit_manifest(manifest, columns={"wet_bulb": {"unit": "degC"}})
    with pytest.raises(ManifestInvalid, match="wet_bulb"):
        load_series(manifest)


def test_a_file_outside_the_dataset_directory_is_refused(tmp_path: Path) -> None:
    manifest = write(tmp_path / "set", ["20.0", "22.0"])
    edit_manifest(manifest, series_file="../series.csv")
    with pytest.raises(ManifestInvalid, match="inside the dataset directory"):
        load_series(manifest)


def test_naive_or_local_timestamps_are_refused(tmp_path: Path) -> None:
    (tmp_path / "series.csv").write_text("time_utc,dry_bulb\n2020-07-01 00:00:00,20.0\n", "utf-8")
    with pytest.raises(ManifestInvalid, match="UTC"):
        write_manifest(
            tmp_path / "series.csv", dataset_id="s", title="t", source="t", version="1",
            licence="none", redistribution="not_cleared", quality_status="synthetic",
            units={"dry_bulb": "degC"}, gap_tolerance_s=0,
        )  # fmt: skip


def test_timestamps_off_the_declared_step_are_refused(tmp_path: Path) -> None:
    lines = ["time_utc,dry_bulb", f"{T0},20.0", "2020-07-01T00:30:00Z,21.0"]
    (tmp_path / "series.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    with pytest.raises(ManifestInvalid, match="step"):
        write_manifest(
            tmp_path / "series.csv", dataset_id="s", title="t", source="t", version="1",
            licence="none", redistribution="not_cleared", quality_status="synthetic",
            units={"dry_bulb": "degC"}, gap_tolerance_s=0,
        )  # fmt: skip


def test_a_period_that_does_not_match_the_file_is_refused(tmp_path: Path) -> None:
    manifest = write(tmp_path, ["20.0", "22.0"])
    edit_manifest(manifest, period={"start_utc": T0, "end_utc": "2020-07-02T00:00:00Z"})
    with pytest.raises(ManifestInvalid, match="period"):
        load_series(manifest)


def test_parse_utc_requires_an_explicit_utc_designator() -> None:
    assert parse_utc_ms("1970-01-01T00:00:01Z") == 1000
    with pytest.raises(ValueError, match="UTC"):
        parse_utc_ms("1970-01-01T00:00:01")
